  public boolean ValidadarDatos() {
        if (txtNombre.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "por favor complete el campo del nombre");
            txtNombre.requestFocus();
        } else if (txtApellido.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "por favor complete el campo del apellido");
            txtApellido.requestFocus();
        } else if (txtTelefono.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "por favor complete el campo del telefono");
            txtTelefono.requestFocus();
        } else if (txtCorreo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "por favor complete el campo del correo");
            txtCorreo.requestFocus();
        } else {
            alumno alum = new alumno();
            alum.setNombre(txtNombre.getText());
            alum.setApellido(txtApellido.getText());
            alum.setTelefono(txtTelefono.getText());
            alum.setCorreo(txtCorreo.getText());
            boolean guardar = alumnoDataChange.guardado(alum);
            if (guardar) {
                LimpiarCampos();
            }

        }
        JOptionPane.showMessageDialog(null, alumnoDataChange.mensaje);
        return false;

    }

    public void LimpiarCampos() {
        txtNombre.setText("");
        txtApellido.setText("");
        txtTelefono.setText("");
        txtCorreo.setText("");
    }
